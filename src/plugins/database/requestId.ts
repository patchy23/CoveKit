/**
 * 执行请求身份
 *
 * 用途：每次执行 SQL / DDL 生成一个唯一标识，随 `dbc_execute` 上报给后端登记取消句柄，
 * 取消（`dbc_cancel`）按该标识命中，结果回填也按它判定归属。
 * 为什么需要：同一连接可以同时有多个在途请求（同连接多页签），后端若只按连接登记取消句柄，
 * 取消一个页签会连带影响另一个；页签切换后按「当前活动页签」回填结果也会写错页签。
 *
 * 标识只在本进程内传递，不落库、不含用户数据；`scope` 传页签 id 或调用方名称，便于排查日志。
 */
let seq = 0

/** 生成新的请求身份（形如 `q-conn-a#1`，同一会话内不重复） */
export function nextRequestId(scope: string): string {
  seq += 1
  return `${scope}#${seq}`
}
